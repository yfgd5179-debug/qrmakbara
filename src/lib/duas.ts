/**
 * Quranic readings and duas customarily recited for the deceased.
 *
 * The Arabic source text is identical in every locale (it is the recited
 * wording itself), so it lives here rather than in the dictionaries — only
 * the short labels are translated, in src/lib/dicts/*.
 */

export type DuaItem = {
  /** Stable key; also the key of the label in `dict.duas.items`. */
  id: string;
  /** Arabic heading, e.g. "سورة الفاتحة". */
  title: string;
  /** Arabic body to recite — masculine form, the conventional default. */
  text: string;
  /** Feminine wording, used when the memorial records `gender: "female"`. */
  textF?: string;
  /** Short Arabic note, e.g. "تُقرأ ثلاثاً". */
  note?: string;
};

